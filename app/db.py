"""PostgreSQL persistence (REQ-07, REQ-14, REQ-15).

All writes are INSERTs inside a single transaction; there is no UPDATE or DELETE
path in the application. IDs are generated by the database (INC-001, EVD-001, ...)
and are reset by POST /reset (TRUNCATE ... RESTART IDENTITY).
"""

from __future__ import annotations

from importlib import resources
from typing import Any

from psycopg import Connection
from psycopg.rows import DictRow, dict_row
from psycopg_pool import ConnectionPool

from .validation import EvidenceInput, IncidentInput

_SCHEMA_LOCK_ID = 74210931  # arbitrary constant for pg_advisory_xact_lock


class Store:
    def __init__(self, database_url: str) -> None:
        self.pool: ConnectionPool[Connection[DictRow]] = ConnectionPool(
            database_url,
            connection_class=Connection[DictRow],
            min_size=1,
            max_size=5,
            kwargs={"row_factory": dict_row},
            open=False,
        )

    def open(self) -> None:
        self.pool.open(wait=True, timeout=30)
        schema = resources.files("app").joinpath("schema.sql").read_text()
        with self.pool.connection() as conn, conn.transaction():
            conn.execute("SELECT pg_advisory_xact_lock(%s)", (_SCHEMA_LOCK_ID,))
            conn.execute(schema)

    def close(self) -> None:
        self.pool.close()

    def ping(self) -> bool:
        try:
            with self.pool.connection(timeout=5) as conn:
                conn.execute("SELECT 1")
            return True
        except Exception:
            return False

    # ---- incidents -------------------------------------------------------

    def create_incident(self, inc: IncidentInput) -> dict[str, Any]:
        with self.pool.connection() as conn, conn.transaction():
            row = conn.execute(
                """
                INSERT INTO incidents (title, description, discovered_at, reporter_name)
                VALUES (%s, %s, %s, %s)
                RETURNING seq, incident_id, created_at
                """,
                (inc.title, inc.description, inc.discovered_at, inc.reporter_name),
            ).fetchone()
            assert row is not None
            conn.execute(
                "INSERT INTO events (incident_seq, event_type, reference_id, recorded_at)"
                " VALUES (%s, 'INCIDENT_CREATED', %s, %s)",
                (row["seq"], row["incident_id"], row["created_at"]),
            )
        return row

    def find_incident_seq(self, incident_id: str) -> int | None:
        with self.pool.connection() as conn:
            row = conn.execute("SELECT seq FROM incidents WHERE incident_id = %s", (incident_id,)).fetchone()
        return None if row is None else int(row["seq"])

    def get_incident(self, incident_id: str) -> tuple[dict[str, Any], list[dict[str, Any]]] | None:
        with self.pool.connection() as conn:
            inc = conn.execute(
                "SELECT seq, incident_id, title, description, discovered_at, reporter_name"
                " FROM incidents WHERE incident_id = %s",
                (incident_id,),
            ).fetchone()
            if inc is None:
                return None
            evidence = conn.execute(
                "SELECT evidence_id, category, summary, source, collected_at, recorded_at"
                " FROM evidence WHERE incident_seq = %s ORDER BY seq",
                (inc["seq"],),
            ).fetchall()
        return inc, evidence

    # ---- evidence --------------------------------------------------------

    def add_evidence(self, incident_seq: int, ev: EvidenceInput) -> dict[str, Any]:
        with self.pool.connection() as conn, conn.transaction():
            row = conn.execute(
                """
                INSERT INTO evidence (incident_seq, category, summary, source, collected_at)
                VALUES (%s, %s, %s, %s, %s)
                RETURNING evidence_id, recorded_at
                """,
                (incident_seq, ev.category, ev.summary, ev.source, ev.collected_at),
            ).fetchone()
            assert row is not None
            conn.execute(
                "INSERT INTO events (incident_seq, event_type, reference_id, recorded_at)"
                " VALUES (%s, 'EVIDENCE_ADDED', %s, %s)",
                (incident_seq, row["evidence_id"], row["recorded_at"]),
            )
        return row

    # ---- test support ----------------------------------------------------

    def reset(self) -> None:
        with self.pool.connection() as conn, conn.transaction():
            conn.execute("TRUNCATE events, evidence, incidents RESTART IDENTITY")
